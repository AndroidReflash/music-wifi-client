package enums

/**
 * Действие, на которое назначается горячая клавиша. Порядок — порядок значков в настройках: пять
 * кнопок управления слева направо, за ними перемотка, за ней громкость.
 *
 * [repeats] — повторяется ли действие, пока клавишу держат. Перемотка и громкость повторяются, как
 * в любом плеере; остальное срабатывает раз на нажатие. Записано здесь, а не у источника нажатий:
 * окно и глобальный перехват повторяют по-разному, но что повторять — одно на всех.
 */
enum class HotkeyAction(val repeats: Boolean) {

    SHUFFLE(repeats = false),
    PREVIOUS(repeats = false),
    PLAY_PAUSE(repeats = false),
    NEXT(repeats = false),
    REPEAT(repeats = false),

    /** Назад на пять секунд. */
    REWIND(repeats = true),

    /** Вперёд на пять секунд. */
    FORWARD(repeats = true),

    /** Громкость приложения на шаг тише. Системную не трогает. */
    VOLUME_DOWN(repeats = true),

    /** Громкость приложения на шаг громче. */
    VOLUME_UP(repeats = true),
}
