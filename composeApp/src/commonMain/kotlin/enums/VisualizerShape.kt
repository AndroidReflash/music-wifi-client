package enums

/**
 * Каким рисовать спектр. Выбирает расстановка: на телефоне полосы идут фоном во всю ширину, а на
 * десктопе спектр живёт в одном квадрате с пластинкой, и там ему идёт кольцо.
 */
enum class VisualizerShape {

    /** Полосы в ряд, зеркально от середины. */
    BARS,

    /** Лучи по кольцу вокруг середины. */
    RING,
}
