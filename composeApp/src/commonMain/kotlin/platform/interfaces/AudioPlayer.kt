package platform.interfaces

import dataClasses.PlaybackSnapshot
import dataClasses.TrackInfo
import enums.PlaybackRepeat
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.StateFlow
import sealedInterfaces.PlaybackEvent

/**
 * Устройство, которое играет. Оно ничего не хранит и ни на что не отвечает: очередь,
 * состояние и порядок действий — дело репозитория, здесь только приказы, снимок и
 * события.
 *
 * Всё, что может не получиться, бросает [sealedInterfaces.PlaybackFailure].
 *
 * Закрывать обязательно: за интерфейсом живёт объект, владеющий потоками и устройством
 * вывода.
 */
interface AudioPlayer : AutoCloseable {

    /**
     * События плеера. Получатель ровно один: каждое событие достаётся тому, кто первым
     * его взял.
     */
    val events: Flow<PlaybackEvent>

    /**
     * Задаёт очередь. `start` — номер дорожки, с которой начинать; `null` означает
     * «с первой». Играть не начинает: для этого есть [play].
     */
    fun setQueue(tracks: List<TrackInfo>, start: Int?)

    /** Играть: продолжить после паузы или начать текущую дорожку очереди. */
    fun play()

    fun pause()

    /** Играть дорожку с таким номером в списке. */
    fun playTrack(index: Int)

    /** Перематывает текущую дорожку на такую миллисекунду. Без дорожки не делает ничего. */
    fun seek(positionMs: Long)

    /** Следующая дорожка. На краю списка без повтора не делает ничего. */
    fun next()

    fun previous()

    /** Обрывает дорожку. Очередь и место в ней сохраняются. */
    fun stop()

    fun setShuffle(shuffle: Boolean)

    fun setRepeat(repeat: PlaybackRepeat)

    /**
     * Подключает плеер к серверу: сетевые дорожки читаются оттуда напрямую. Пустой
     * адрес означает «сервера нет», и прежнее подключение тогда отпускается.
     *
     * Подключение живёт отдельно от плеера: адрес вводят уже после запуска и меняют на
     * ходу, а пересоздавать плеер вместе с устройством вывода ради этого незачем.
     * Играющую дорожку смена не трогает — она дочитывает через прежнее подключение.
     */
    fun connect(address: String)

    /**
     * Имена устройств, на которые можно вывести звук. В списке только те, на которых он
     * действительно заиграет.
     *
     * Вызов не быстрый: у каждого устройства спрашивают формат, а это разговор с системой.
     * Звать его надо тогда, когда открывают настройки, и не из главного потока.
     */
    fun outputDevices(): List<String>

    /**
     * Куда выводить звук. `null` — то устройство, которое система считает основным.
     *
     * Дорожка продолжает играть; пропадёт только то, что лежало в буфере прежнего устройства.
     * Если устройство не открылось, звук остаётся на прежнем, а беда придёт событием.
     */
    fun setOutputDevice(name: String?)

    /**
     * Байты вложенной картинки дорожки — обложки, как они лежат в файле. `null` означает, что её
     * в файле нет, и это обычное дело, а не беда.
     *
     * Путь — к файлу на этой машине: у дорожки с сервера обложки не будет. Вызов читает файл,
     * поэтому не из главного потока.
     */
    fun trackCover(path: String): ByteArray?

    /**
     * Громкость самого приложения, от 0 до 1 — не системная. Действует сразу: множится то, что
     * плеер отдаёт устройству.
     */
    fun setVolume(volume: Float)

    /**
     * Центры полос эквалайзера, Гц, от низкой к высокой. Их число — то, сколько усилений ждёт
     * [setEqualizer]. Плеер для ответа не нужен: это постоянные ядра.
     */
    fun equalizerBands(): List<Float>

    /** Предел подъёма и ослабления полосы, дБ: ползунок ходит от минус этого числа до плюс него. */
    fun equalizerMaxDb(): Float

    /**
     * Усиления полос, дБ, по одному на каждую из [equalizerBands], в том же порядке. Действует
     * сразу, как и громкость. Звук ослабляется на самый большой подъём, чтобы поднятая полоса не
     * вывела его за предел устройства.
     */
    fun setEqualizer(gainsDb: List<Float>)

    /**
     * Полосы спектра. Приходят сами, в тот миг, когда кадры уходят устройству, — темп
     * задаёт звук, а не таймер. Значение заменяется целиком: опоздавший рисовальщик
     * пропустит кадр, а не разберёт очередь старых.
     */
    val bands: StateFlow<List<Double>>

    /** Состояние на сейчас, включая позицию. */
    fun snapshot(): PlaybackSnapshot
}
