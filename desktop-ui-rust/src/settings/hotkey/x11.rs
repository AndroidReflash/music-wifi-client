use iced::keyboard::key::Code;

use super::physical::PhysicalKeyId;

pub fn keysym(id: PhysicalKeyId) -> Option<u32> {
    match id {
        PhysicalKeyId::Code(code) => keysym_for_code(code),
        PhysicalKeyId::Xkb(_) => None,
    }
}

